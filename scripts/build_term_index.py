#!/usr/bin/env python3
"""Build a project's term-occurrence index from its term register (docs/term-index-protocol.md).

Purpose: the engine and the writing commands. A project keeps coded definitions in
    <project>/terminology/terms.json. This script finds every occurrence of each registered form in the
    project's documents and writes, beside the register: term-index.json (manifest of content hashes),
    index/<doc>.json (one per document) and glossary.md (a reading view of the register).
Lifecycle: UTILITY
Created: 2026-11-16

CEILING (do not soften): a current index establishes that the register is well formed and that the index
matches the documents, not that a term is used in its defined sense. Matching finds forms, not meanings.

Usage:
  python3 scripts/build_term_index.py build [project]   rebuild one project, or every registered one
  python3 scripts/build_term_index.py init <project>    write a starter register (never overwrites)
  python3 scripts/build_term_index.py hook              Claude Code hook: payload on stdin
Exit codes: build/init 0 ok, 1 defect, 2 usage error. hook: 0 done or nothing to do, 2 feedback for the
agent about the file just edited. Env: RT_ROOT=<path> overrides the repository root (test harness).

check_term_index.py and query_term_index.py import this module, so there is one matcher. Standard library
only; no network and no child processes. Generated files hold no timestamps and no absolute paths.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

GENERATOR = "researchteam-term-index/1"
REGISTER_SCHEMA = "researchteam-term-register"
CEILING = ("A current index establishes that the register is well formed and that the index matches "
           "the documents. It does not establish that a term is used in its defined sense. "
           "Matching finds forms, not meanings.")
DO_NOT_EDIT = ("GENERATED by scripts/build_term_index.py from terminology/terms.json. Do not edit. "
               "Rebuild: bash scripts/claude_researchteam_bridge.sh term-build <project>")
MAX_TERMS, MAX_FORMS, MAX_FORM_CHARS = 5000, 50, 200
MAX_REGISTER_BYTES, MAX_DOC_BYTES, MAX_STDIN = 1_000_000, 5_000_000, 1_000_000
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
TERM_KEYS = {"id", "label", "definition", "variants", "discouraged", "source", "notes", "plural"}
TOP_KEYS = {"schema", "schema_version", "scope", "terms", "allow"}
# The citation detector's reference-list headings (scripts/check_citation_integrity.sh, split_deliverable).
REFS_HEADING = re.compile(r"^#{1,6}[ \t]+([Rr]eferences|[Bb]ibliography|[Ww]orks [Cc]ited|[Ss]ources)([ \t].*)?$")
HEADING = re.compile(r"^#{1,6}[ \t]+")
SEP = r"[*_]{0,3}(?:[ \t]+|[ \t]*\n(?:[ \t]*>)*[ \t]*|-)[*_]{0,3}"
STARTER = {"schema": REGISTER_SCHEMA, "schema_version": "1.0", "scope": {"include": ["**/*.md"], "exclude": []}, "terms": [], "allow": []}


def repo_root() -> Path:
    return Path(os.environ.get("RT_ROOT") or Path(__file__).parent.parent).resolve()


def is_research_project(d: Path) -> bool:
    return any(re.match(r"\d\d-.*\.md$", p.name) for p in d.iterdir() if p.is_file())


def discover(root: Path) -> list[Path]:
    """Project directories under Projects/, at any depth. A project is not searched for projects."""
    found: list[Path] = []

    def walk(d: Path, depth: int) -> None:
        for child in sorted(p for p in d.iterdir() if p.is_dir() and not p.is_symlink()):
            if child.name.startswith(".") or not NAME_RE.match(child.name):
                continue
            tdir = child / "terminology"
            if (tdir / "terms.json").exists() or (tdir / "term-index.json").exists() or is_research_project(child):
                found.append(child)
            elif depth < 4:
                walk(child, depth + 1)

    base = root / "Projects"
    if base.is_dir() and not base.is_symlink():
        walk(base, 1)
    return found


def resolve(root: Path, target: str) -> Path | None:
    """A project by its path under Projects/ or by its directory name. None when absent or unsafe."""
    parts = [p for p in target.replace("\\", "/").strip("/").split("/") if p]
    if parts[:1] == ["Projects"]:
        parts = parts[1:]
    if not parts or not all(NAME_RE.match(p) for p in parts):
        return None
    direct = root.joinpath("Projects", *parts)
    if direct.is_dir() and not any(p.is_symlink() for p in (direct, *direct.parents) if root in p.parents):
        return direct
    named = [p for p in discover(root) if p.name == parts[-1]] if len(parts) == 1 else []
    return named[0] if len(named) == 1 else None


def norm(form: str) -> str:
    return " ".join(re.split(r"[\s-]+", form.strip().casefold()))


def _strings(value, what: str, where: str, problems: list) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
        problems.append(("SCHEMA", f"{where}: '{what}' must be a list of non-empty strings"))
        return []
    return value


def load_register(proj: Path):
    """Return (status, register, problems). status: missing | foreign | bad | ok.

    'foreign' is a terms.json without the researchteam schema marker: not ours, so never a defect.
    """
    tdir, path = proj / "terminology", proj / "terminology" / "terms.json"
    if tdir.is_symlink() or path.is_symlink():
        return "bad", None, [("SCHEMA", "terminology/ or terms.json is a symbolic link (refused)")]
    if not path.is_file():
        return "missing", None, []
    if path.stat().st_size > MAX_REGISTER_BYTES:
        return "bad", None, [("SCHEMA", f"terms.json is larger than {MAX_REGISTER_BYTES} bytes")]
    try:
        reg = json.loads(path.read_bytes().decode("utf-8"))
    except (OSError, UnicodeDecodeError) as exc:
        return "bad", None, [("SCHEMA", f"terms.json cannot be read ({type(exc).__name__})")]
    except json.JSONDecodeError as exc:
        return "bad", None, [("SCHEMA", f"terms.json is not valid JSON at line {exc.lineno}, column {exc.colno}")]
    if not isinstance(reg, dict) or reg.get("schema") != REGISTER_SCHEMA:
        return "foreign", None, []
    problems: list = [("SCHEMA", "unknown top-level key")] if set(reg) - TOP_KEYS else []
    terms = reg.get("terms")
    if not isinstance(terms, list) or len(terms) > MAX_TERMS:
        return "bad", None, problems + [("SCHEMA", f"'terms' must be a list of at most {MAX_TERMS} records")]
    seen: set[str] = set()
    for n, term in enumerate(terms, 1):
        where = f"term {n}"
        if not isinstance(term, dict):
            problems.append(("SCHEMA", f"{where}: must be an object"))
            continue
        tid = term.get("id")
        if not isinstance(tid, str) or not ID_RE.match(tid):
            problems.append(("SCHEMA", f"{where}: 'id' must be a lower-case slug (letters, digits, hyphens)"))
            continue
        where = f"term '{tid}'"
        if tid in seen:
            problems.append(("SCHEMA", f"{where}: id is defined more than once"))
        seen.add(tid)
        if set(term) - TERM_KEYS:
            problems.append(("SCHEMA", f"{where}: unknown key (allowed: {', '.join(sorted(TERM_KEYS))})"))
        for key in ("label", "definition"):
            if not isinstance(term.get(key), str) or not term[key].strip():
                problems.append(("SCHEMA", f"{where}: '{key}' must be a non-empty string"))
        forms = [term.get("label")] if isinstance(term.get("label"), str) else []
        for key in ("variants", "discouraged"):
            if key in term:
                forms += _strings(term[key], key, where, problems)
        if len(forms) > MAX_FORMS or any(len(f) > MAX_FORM_CHARS or not norm(f) for f in forms):
            problems.append(("SCHEMA", f"{where}: at most {MAX_FORMS} forms, each 1 to {MAX_FORM_CHARS} characters"))
        if not isinstance(term.get("plural", True), bool):
            problems.append(("SCHEMA", f"{where}: 'plural' must be true or false"))
        if "notes" in term and not isinstance(term["notes"], str):
            problems.append(("SCHEMA", f"{where}: 'notes' must be a string"))
        src = term.get("source")
        if src is not None and src != "project definition" and not (
                isinstance(src, list) and src and all(isinstance(k, str) and k.strip() for k in src)):
            problems.append(("SCHEMA", f"{where}: 'source' must be \"project definition\" or a list of .bib keys"))
    scope = reg.get("scope", {})
    if not isinstance(scope, dict) or set(scope) - {"include", "exclude"}:
        problems.append(("SCHEMA", "'scope' must be an object with 'include' and/or 'exclude'"))
    else:
        for key in scope:
            for pat in _strings(scope[key], key, "scope", problems):
                if pat.startswith("/") or ".." in pat.split("/") or "\\" in pat:
                    problems.append(("SCOPE", f"scope pattern {scope[key].index(pat) + 1} in '{key}' is absolute or leaves the project"))
    for n, entry in enumerate(reg.get("allow", []) if isinstance(reg.get("allow", []), list) else [None], 1):
        ok = (isinstance(entry, dict) and set(entry) == {"term", "file", "reason"}
              and all(isinstance(entry[k], str) and entry[k].strip() for k in entry))
        if not ok:
            problems.append(("SCHEMA", f"allow entry {n}: needs exactly 'term', 'file' and 'reason' (strings)"))
        elif entry["term"] not in seen:
            problems.append(("SCHEMA", f"allow entry {n}: names a term id that is not registered"))
    if not any(code == "SCHEMA" for code, _ in problems):
        problems += _ambiguities(terms)
    return ("bad" if problems else "ok"), reg, problems


def term_forms(term: dict):
    """(form, kind) for a term: the label, its variants and its discouraged forms."""
    yield term["label"], "label"
    for v in term.get("variants", []):
        yield v, "variant"
    for v in term.get("discouraged", []):
        yield v, "discouraged"


def _ambiguities(terms: list) -> list:
    owner: dict[str, tuple[str, bool]] = {}
    out = []
    for term in terms:
        for form, kind in term_forms(term):
            keys = {norm(form)}
            if term.get("plural", True):
                keys |= {norm(form) + "s", norm(form) + "es"}
            for key in keys:
                prev = owner.setdefault(key, (term["id"], kind == "discouraged"))
                if prev[0] != term["id"]:
                    out.append(("AMBIG", f"terms '{prev[0]}' and '{term['id']}' claim the same form"))
                elif prev[1] != (kind == "discouraged"):
                    out.append(("AMBIG", f"term '{term['id']}' lists one form as both accepted and discouraged"))
    return sorted(set(out))


def glob_regex(pattern: str) -> re.Pattern:
    """Translate a scope glob over POSIX relative paths. Own matcher: pathlib differs across versions."""
    table = {"**/": "(?:.*/)?", "**": ".*", "*": "[^/]*", "?": "[^/]"}
    parts = re.split(r"(\*\*/|\*\*|\*|\?)", pattern)
    return re.compile("".join(table.get(p, re.escape(p)) for p in parts) + r"\Z")


def documents(proj: Path, reg: dict) -> list[str]:
    scope = reg.get("scope", {})
    include = [glob_regex(p) for p in scope.get("include", ["**/*.md"])]
    exclude = [glob_regex(p) for p in scope.get("exclude", [])]
    found = []
    for base, dirs, files in os.walk(proj, followlinks=False):
        dirs[:] = sorted(d for d in dirs if not (Path(base) / d).is_symlink())
        for name in sorted(files):
            full = Path(base) / name
            rel = full.relative_to(proj).as_posix()
            if full.is_symlink() or rel.startswith("terminology/"):
                continue  # terminology/ is never indexed: the glossary would index itself
            if any(r.match(rel) for r in include) and not any(r.match(rel) for r in exclude):
                found.append(rel)
    return sorted(found)


def mask(text: str) -> str:
    """Blank out what is not prose, keeping every offset and line break in place."""
    chars = list(text)

    def blank(start: int, end: int) -> None:
        for i in range(start, end):
            if chars[i] != "\n":
                chars[i] = "\x00"

    pos, fence, in_refs = 0, "", False
    front = re.match(r"---\n.*?\n---[ \t]*\n", text, re.S)
    for line in text.splitlines(keepends=True):
        end, body = pos + len(line), line.strip()
        if front and end <= front.end():
            blank(pos, end)
        elif fence:
            blank(pos, end)
            if body.startswith(fence):
                fence = ""
        elif body.startswith("```") or body.startswith("~~~"):
            fence = body[:3]
            blank(pos, end)
        elif HEADING.match(line):
            in_refs = REFS_HEADING.match(line.rstrip("\n")) is not None
            if in_refs:
                blank(pos, end)
            if line.endswith("\n"):
                chars[end - 1] = "\x00"  # a match never runs out of a heading
        elif in_refs:
            blank(pos, end)
        pos = end
    masked = "".join(chars)
    for pattern in (r"<!--.*?-->", r"`[^`\n]*`", r"(?<=\])\([^)\s]*\)", r"<?https?://[^\s<>)]+>?"):
        for m in re.finditer(pattern, masked, re.S):
            blank(m.start(), m.end())
    return "".join(chars)


def quoted_spans(masked: str) -> list[tuple[int, int]]:
    spans, pos = [], 0
    for line in masked.splitlines(keepends=True):
        if line.lstrip(" \t").startswith(">"):
            spans.append((pos, pos + len(line)))
        pos += len(line)
    for para in re.finditer(r"(?:[^\n]+\n?)+", masked):
        text, base = para.group(), para.start()
        spans += [(base + m.start(), base + m.end()) for m in re.finditer(r"“[^”]*”", text)]
        marks = [m.start() for m in re.finditer(r'"', text)]
        if len(marks) % 2 == 0:  # an odd number of straight marks exempts nothing
            spans += [(base + a, base + b) for a, b in zip(marks[::2], marks[1::2])]
    return spans


def form_pattern(form: str, plural: bool) -> re.Pattern:
    body = SEP.join(re.escape(tok) for tok in re.split(r"[\s-]+", form.strip()) if tok)
    body += "(?:e?s)?" if plural else ""
    flags = re.I if form == form.lower() else 0
    return re.compile(r"(?<![^\W_])(?<!-)" + body + r"(?![^\W_])(?!-)", flags)


def occurrences(text: str, reg: dict) -> list[dict]:
    masked = mask(text)
    hits = []
    for term in reg["terms"]:
        for form, kind in term_forms(term):
            for m in form_pattern(form, term.get("plural", True)).finditer(masked):
                hits.append((m.end() - m.start(), m.start(), m.end(), term["id"], form, kind))
    spans, taken, out = quoted_spans(masked), [], []
    for _, start, end, tid, form, kind in sorted(hits, key=lambda h: (-h[0], h[1], h[3], h[4])):
        if any(start < e and s < end for s, e in taken):
            continue  # the longest match wins where forms overlap
        taken.append((start, end))
        line = text.count("\n", 0, start) + 1
        out.append({"term": tid, "line": line, "column": start - (text.rfind("\n", 0, start) + 1) + 1,
                    "form": form, "kind": kind, "quoted": any(s <= start < e for s, e in spans)})
    return sorted(out, key=lambda o: (o["line"], o["column"]))


def scan(proj: Path, reg: dict):
    """Return ({document: (sha256, occurrences)}, problems)."""
    docs, problems = {}, []
    names = documents(proj, reg)
    if not names:
        problems.append(("SCOPE", "the scope matches no document"))
    for rel in names:
        raw = (proj / rel).read_bytes()
        if len(raw) > MAX_DOC_BYTES:
            problems.append(("SCOPE", f"{rel}: larger than {MAX_DOC_BYTES} bytes"))
            continue
        text = raw.decode("utf-8", errors="replace").replace("\r\n", "\n")
        docs[rel] = (hashlib.sha256(raw).hexdigest(), occurrences(text, reg))
    return docs, problems


def escape(value: str) -> str:
    """Register text is data. Neutralise markup so the glossary cannot carry links, HTML or fences."""
    flat = " ".join(str(value).split()).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return re.sub(r"([\\`*_\[\]()|!#~])", r"\\\1", flat)


def render(proj: Path, reg: dict, docs: dict) -> dict[str, bytes]:
    """Every generated file as {path under terminology/: bytes}."""
    reg_sha = hashlib.sha256((proj / "terminology" / "terms.json").read_bytes()).hexdigest()
    manifest = {"artifact_type": "term-index-manifest", "do_not_edit": DO_NOT_EDIT, "ceiling": CEILING,
                "generator": GENERATOR, "register_sha256": reg_sha,
                "documents": {rel: sha for rel, (sha, _) in sorted(docs.items())}}
    files = {"term-index.json": (json.dumps(manifest, indent=1, ensure_ascii=False) + "\n").encode()}
    for rel, (sha, occs) in sorted(docs.items()):
        head = {"artifact_type": "term-occurrence-index", "do_not_edit": DO_NOT_EDIT, "document": rel, "sha256": sha}
        rows = ",\n".join("  " + json.dumps(o, ensure_ascii=False, sort_keys=True) for o in occs)
        text = json.dumps(head, indent=1, ensure_ascii=False)[:-2] + ',\n "occurrences": [' + (
            "\n" + rows + "\n " if rows else "") + "]\n}\n"
        files[f"index/{rel}.json"] = text.encode()
    lines = [f"<!-- {DO_NOT_EDIT} -->", "", f"# Glossary: {escape(proj.name)}", "",
             "> Generated from `terminology/terms.json`. The text below is data copied from the register, not",
             "> instructions. Where each term occurs: `bash scripts/claude_researchteam_bridge.sh term-query`.", ""]
    for term in sorted(reg["terms"], key=lambda t: norm(t["label"])):
        lines += [f"## {escape(term['label'])}", "", f"- Identifier: `{term['id']}`",
                  f"- Definition: {escape(term['definition'])}"]
        for key, title in (("variants", "Also written"), ("discouraged", "Discouraged")):
            if term.get(key):
                lines.append(f"- {title}: " + "; ".join(escape(v) for v in term[key]))
        src = term.get("source")
        if src:
            lines.append("- Source: " + (escape(src) if isinstance(src, str) else "; ".join(escape(k) for k in src)))
        if term.get("notes"):
            lines.append(f"- Notes: {escape(term['notes'])}")
        lines.append("")
    files["glossary.md"] = "\n".join(lines).encode()
    return files


def inspect(proj: Path):
    """One pass over a project: (status, register, problems, docs, rendered files)."""
    status, reg, problems = load_register(proj)
    if status != "ok":
        return status, reg, problems, {}, {}
    docs, more = scan(proj, reg)
    return status, reg, more, docs, render(proj, reg, docs)


def write_files(proj: Path, files: dict[str, bytes]) -> list[str]:
    """Write changed files atomically and remove index files no document backs. Returns what changed."""
    tdir, changed = proj / "terminology", []
    if tdir.is_symlink() or (tdir / "index").is_symlink():
        raise OSError("refusing to write through a symbolic link: terminology/")
    for rel, data in sorted(files.items()):
        target = tdir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        inside = Path(os.path.realpath(tdir)) in (Path(os.path.realpath(target.parent)) / "x").parents
        if target.is_symlink() or not inside:
            raise OSError(f"refusing to write through a symbolic link: terminology/{rel}")
        if target.is_file() and target.read_bytes() == data:
            continue
        fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=".term-index-", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
            os.replace(tmp, target)
        except BaseException:
            os.unlink(tmp)
            raise
        changed.append(rel)
    for stale in sorted(extra_index_files(proj, files)):
        (tdir / stale).unlink()
        changed.append(stale)
    for d in sorted((p for p in (tdir / "index").rglob("*") if p.is_dir()), reverse=True):
        if not any(d.iterdir()):
            d.rmdir()
    return changed


def extra_index_files(proj: Path, files: dict[str, bytes]) -> set[str]:
    index = proj / "terminology" / "index"
    if not index.is_dir() or index.is_symlink():
        return set()
    on_disk = {p.relative_to(proj / "terminology").as_posix() for p in index.rglob("*.json") if p.is_file()}
    return on_disk - set(files)


def rebuild(proj: Path):
    """Inspect and write under one lock, so two builds cannot interleave. Returns inspect() plus what changed.

    The lock is taken before the documents are read: a build that waited sees the other build's inputs.
    """
    tdir, fd = proj / "terminology", None
    try:
        import fcntl  # POSIX only; elsewhere the atomic replace still keeps every file whole
        if tdir.is_dir() and not tdir.is_symlink():
            fd = os.open(tdir, os.O_RDONLY)
            fcntl.flock(fd, fcntl.LOCK_EX)
    except ImportError:
        pass
    try:
        status, reg, problems, docs, files = inspect(proj)
        return status, reg, problems, docs, (write_files(proj, files) if status == "ok" and not problems else None)
    finally:
        if fd is not None:
            os.close(fd)


def build(proj: Path) -> tuple[int, list[str]]:
    """Rebuild one project. Returns (exit code, messages)."""
    try:
        status, _, problems, docs, changed = rebuild(proj)
    except OSError as exc:
        return 1, [f"not written: {exc}"]
    if status in ("missing", "foreign"):
        return 1, ["no term register (run: term-init)"]
    if changed is None:
        return 1, [f"DEFECT[{code}] {msg}" for code, msg in problems]
    return 0, [f"{len(docs)} documents indexed, {len(changed)} generated files written"]


def cmd_build(args: list[str]) -> int:
    root = repo_root()
    if len(args) > 1:
        print("usage: build_term_index.py build [project]", file=sys.stderr)
        return 2
    targets = [p for p in discover(root) if load_register(p)[0] not in ("missing", "foreign")]
    if args:
        targets = [resolve(root, args[0])]
        if targets[0] is None:
            print(f"ERROR: project not found under Projects/: {args[0]}", file=sys.stderr)
            return 2
    worst = 0
    for proj in targets:
        code, messages = build(proj)
        worst = max(worst, code)
        for msg in messages:
            print(f"{proj.relative_to(root).as_posix()}: {msg}")
    if not targets:
        print("No project has a term register; nothing was built.")
    return worst


def cmd_init(args: list[str]) -> int:
    root = repo_root()
    proj = resolve(root, args[0]) if len(args) == 1 else None
    if proj is None:
        print("usage: build_term_index.py init <project>   (the project directory must exist)", file=sys.stderr)
        return 2
    tdir = proj / "terminology"
    if tdir.is_symlink() or (tdir.exists() and any(tdir.iterdir())):
        print(f"ERROR: {tdir.relative_to(root).as_posix()}/ already exists and is not empty; nothing written.",
              file=sys.stderr)
        return 1
    tdir.mkdir(exist_ok=True)
    (tdir / "terms.json").write_text(json.dumps(STARTER, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {(tdir / 'terms.json').relative_to(root).as_posix()}. Add terms, then run term-build.")
    return 0


def _hook_target(root: Path) -> tuple[Path | None, str]:
    """The path the hook payload names, confined to the repository. ('', '') when there is none."""
    try:
        payload = json.loads(sys.stdin.read(MAX_STDIN))
        tool_input = payload.get("tool_input", {}) if isinstance(payload, dict) else {}
        raw = tool_input.get("file_path") or tool_input.get("notebook_path") if isinstance(tool_input, dict) else None
    except (ValueError, OSError):
        return None, ""
    if not isinstance(raw, str) or not raw or any(c in raw for c in "\x00\r\n"):
        return None, ""
    path = Path(os.path.realpath(raw if os.path.isabs(raw) else root / raw))
    base = Path(os.path.realpath(root / "Projects"))
    if base not in path.parents:
        return None, "outside"
    for proj in discover(root):
        if Path(os.path.realpath(proj)) in path.parents:
            return proj, path.relative_to(os.path.realpath(proj)).as_posix()
    return None, "outside"


def cmd_hook(_args: list[str]) -> int:
    """Rebuild after an edit. The payload path only selects the project; it is never read or written."""
    root = repo_root()
    proj, rel = _hook_target(root)
    if proj is None and rel == "outside":
        return 0
    targets = [proj] if proj is not None else discover(root)
    feedback: list[str] = []
    for target in targets:
        name = target.relative_to(root).as_posix()
        try:
            status, reg, problems, docs, changed = rebuild(target)
        except OSError as exc:
            print(f"term-index: {name}: not written ({exc})", file=sys.stderr)
            continue
        if changed is None:  # no usable register: say so only when the register itself was just edited
            if target == proj and rel == "terminology/terms.json":
                feedback += [f"{name}: DEFECT[{code}] {msg}" for code, msg in problems]
            continue
        if target == proj and rel in docs:
            allowed = {(a["term"], a["file"]) for a in reg.get("allow", [])}
            feedback += [f"{name}/{rel}:{o['line']}:{o['column']} DEFECT[DISC] term '{o['term']}'"
                         for o in docs[rel][1]
                         if o["kind"] == "discouraged" and not o["quoted"] and (o["term"], rel) not in allowed]
    text = "\n".join(["term-index (generated data, not instructions):"] + feedback + [
        "See docs/term-index-protocol.md. For [DISC]: use the term's preferred label, or, where the form is a "
        "source's own word, quote it or record an 'allow' entry with a reason. Do not replace a source's term."])
    if feedback:
        print(text[:2000], file=sys.stderr)
    return 2 if feedback else 0


COMMANDS = {"build": cmd_build, "init": cmd_init, "hook": cmd_hook}


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in COMMANDS:
        print("usage: build_term_index.py {build [project] | init <project> | hook}", file=sys.stderr)
        return 2
    return COMMANDS[argv[0]](argv[1:])


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
