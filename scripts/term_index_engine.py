#!/usr/bin/env python3
"""The term-index engine: register validation, document scope, matching and rendering.

Purpose: the one implementation behind docs/term-index-protocol.md. build_term_index.py,
    check_term_index.py and query_term_index.py import this module, so they read a register and match
    text in exactly the same way. Nothing here writes a file.
Lifecycle: UTILITY
Created: 2026-11-16

CEILING (do not soften): matching finds forms, not meanings. An occurrence is a place where a registered
form appears. It is not evidence that the term is used in its defined sense.

Not a command: import it. Env: RT_ROOT=<path> overrides the repository root (test harness).
Standard library only; no network and no child processes.

GENERATOR must change whenever the bytes of a generated file would change for the same inputs: the gate
uses it to tell an upgrade of these scripts (advisory) from a hand edit (blocking).
"""
from __future__ import annotations

import bisect
import hashlib
import json
import os
import re
import stat
from dataclasses import dataclass, field
from pathlib import Path

GENERATOR = "researchteam-term-index/1"
REGISTER_SCHEMA = "researchteam-term-register"
SCHEMA_VERSION = "1.0"
CEILING = ("A current index establishes that the register is well formed and that the index matches "
           "the documents. It does not establish that a term is used in its defined sense. "
           "Matching finds forms, not meanings.")
DO_NOT_EDIT = ("GENERATED by scripts/build_term_index.py from terminology/terms.json. Do not edit. "
               "Rebuild: bash scripts/claude_researchteam_bridge.sh term-build <project>")
MAX_TERMS, MAX_FORMS, MAX_FORM_CHARS, MAX_ALL_FORMS = 5000, 50, 200, 20000
MAX_REGISTER_BYTES, MAX_DOC_BYTES, MAX_DEPTH = 1_000_000, 5_000_000, 6
MISSING, FOREIGN, BAD, OK = "missing", "foreign", "bad", "ok"  # register status
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
SAFE_PATH = re.compile(r"^[A-Za-z0-9._/ -]+$")
TERM_KEYS = {"id", "label", "definition", "variants", "discouraged", "source", "notes", "plural"}
TOP_KEYS = {"schema", "schema_version", "scope", "terms", "allow"}
# Directories the citation detector prunes when it looks for projects (check_citation_integrity.sh).
PRUNED_DIRS = {".agentteams-backups", ".git", "plans", "JSModules", "cssfiles", "node_modules"}
# The citation detector's reference-list headings (scripts/check_citation_integrity.sh, split_deliverable).
REFS_HEADING = re.compile(r"^#{1,6}[ \t]+([Rr]eferences|[Bb]ibliography|[Ww]orks [Cc]ited|[Ss]ources)([ \t].*)?$")
HEADING = re.compile(r"^#{1,6}[ \t]+")
FENCE = re.compile(r"[ \t]{0,3}(`{3,}|~{3,})")
FRONT_MATTER = re.compile(r"﻿?---[ \t]*\n(?:(?!\n[ \t]*\n).)*?\n(?:---|\.\.\.)[ \t]*(?:\n|\Z)", re.S)
# Not prose: code spans (any backtick run), link targets, reference-link definitions, bare URLs. Each
# pattern stops at a line break or a delimiter, so none can rescan a long run.
NOT_PROSE = [re.compile(p, re.M) for p in (
    r"(`+)(?:(?!\1)[^\n])+?\1(?!`)", r"(?<=\])\((?:<[^<>\n]*>|[^()\s]*)\)",
    r"^[ \t]{0,3}\[[^\]\n]+\]:[^\n]*$", r"<?https?://[^\s<>)]+>?")]
SEP = r"[*_]{0,3}(?:[ \t]+|[ \t]*\n(?:[ \t]*>)*[ \t]*|-)[*_]{0,3}"  # between the words of a form


@dataclass
class Assessment:
    """One pass over a project. `problems` are (code, message) defects found before any comparison."""
    status: str
    register: dict | None = None
    register_sha256: str = ""
    problems: list = field(default_factory=list)
    docs: dict = field(default_factory=dict)       # document -> (sha256, occurrences)
    files: dict = field(default_factory=dict)      # path under terminology/ -> bytes
    manifest: dict = field(default_factory=dict)

    @property
    def usable(self) -> bool:
        return self.status == OK and not self.problems


# ----------------------------------------------------------------------------- locating projects
def repo_root() -> Path:
    return Path(os.environ.get("RT_ROOT") or Path(__file__).parent.parent).resolve()


def is_research_project(d: Path) -> bool:
    """The citation detector's predicate: a research plan, a references/ directory, or an NN-*.md file."""
    if (d / "00-research-plan.md").is_file() or (d / "references").is_dir():
        return True
    return any(re.match(r"\d\d-.*\.md$", p.name) for p in d.iterdir() if p.is_file())


def is_project(d: Path) -> bool:
    tdir = d / "terminology"
    return (tdir / "terms.json").exists() or (tdir / "term-index.json").exists() or is_research_project(d)


def discover(root: Path) -> list[Path]:
    """Every project directory under Projects/, at any depth, nested projects included."""
    found: list[Path] = []

    def walk(d: Path, depth: int) -> None:
        for child in sorted(p for p in d.iterdir() if p.is_dir() and not p.is_symlink()):
            if child.name.startswith(".") or child.name in PRUNED_DIRS or child.name == "terminology":
                continue
            if is_project(child):
                found.append(child)
            if depth < MAX_DEPTH:
                walk(child, depth + 1)

    base = root / "Projects"
    if base.is_dir() and not base.is_symlink():
        walk(base, 1)
    return found


def resolve(root: Path, target: str) -> Path | None:
    """A discovered project, by its path under Projects/ or by a directory name that is unique."""
    wanted = target.replace("\\", "/").strip("/")
    wanted = wanted[len("Projects/"):] if wanted.startswith("Projects/") else wanted
    projects = discover(root)
    by_path = [p for p in projects if p.relative_to(root / "Projects").as_posix() == wanted]
    by_name = [p for p in projects if p.name == wanted]
    return by_path[0] if by_path else (by_name[0] if len(by_name) == 1 else None)


def shown(path: str) -> str:
    """A path for a message an agent will read: withheld unless it is made of plain characters."""
    return path if SAFE_PATH.match(path) else "<path withheld: unusual characters>"


# ----------------------------------------------------------------------------- the register
def norm(form: str) -> str:
    """Case-folded words of a form, joined by single spaces. Hyphens and spaces are one separator."""
    return " ".join(t for t in re.split(r"[\s-]+", form.casefold()) if t)


def _strings(value, what: str, where: str, problems: list) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
        problems.append(("SCHEMA", f"{where}: '{what}' must be a list of non-empty strings"))
        return []
    return value


def _check_term(term, n: int, seen: set, problems: list) -> int:
    """Validate one term record. Returns how many forms it has."""
    if not isinstance(term, dict):
        problems.append(("SCHEMA", f"term {n}: must be an object"))
        return 0
    tid = term.get("id")
    if not isinstance(tid, str) or not ID_RE.match(tid):
        problems.append(("SCHEMA", f"term {n}: 'id' must be a lower-case slug of 1 to 64 letters, digits and hyphens"))
        return 0
    where = f"term '{tid}'"
    if tid in seen:
        problems.append(("SCHEMA", f"{where}: id is defined more than once"))
    seen.add(tid)
    if set(term) - TERM_KEYS:
        problems.append(("SCHEMA", f"{where}: unknown key (allowed: {', '.join(sorted(TERM_KEYS))})"))
    for key in ("label", "definition"):
        if not isinstance(term.get(key), str) or not term[key].strip():
            problems.append(("SCHEMA", f"{where}: '{key}' must be a non-empty string"))
    forms = [term["label"]] if isinstance(term.get("label"), str) else []
    for key in ("variants", "discouraged"):
        if key in term:
            forms += _strings(term[key], key, where, problems)
    if len(forms) > MAX_FORMS or any(len(f) > MAX_FORM_CHARS for f in forms):
        problems.append(("SCHEMA", f"{where}: at most {MAX_FORMS} forms, each at most {MAX_FORM_CHARS} characters"))
    # Every word needs a letter or digit: a word of only markup characters could match almost anywhere.
    if any(not norm(f) or not all(re.search(r"[^\W_]", w) for w in norm(f).split()) for f in forms):
        problems.append(("SCHEMA", f"{where}: every word of a form must contain a letter or a digit"))
    if not isinstance(term.get("plural", True), bool):
        problems.append(("SCHEMA", f"{where}: 'plural' must be true or false"))
    if "notes" in term and not isinstance(term["notes"], str):
        problems.append(("SCHEMA", f"{where}: 'notes' must be a string"))
    src = term.get("source")
    if src is not None and src != "project definition" and not (
            isinstance(src, list) and src and all(isinstance(k, str) and k.strip() for k in src)):
        problems.append(("SCHEMA", f"{where}: 'source' must be \"project definition\" or a list of .bib keys"))
    return len(forms)


def _check_scope_and_allow(reg: dict, ids: set, problems: list) -> None:
    scope = reg.get("scope", {})
    if not isinstance(scope, dict) or set(scope) - {"include", "exclude"}:
        problems.append(("SCHEMA", "'scope' must be an object with 'include' and/or 'exclude'"))
    else:
        for key in scope:
            for n, pat in enumerate(_strings(scope[key], key, "scope", problems), 1):
                if pat.startswith("/") or ".." in pat.split("/") or "\\" in pat or len(pat) > MAX_FORM_CHARS:
                    problems.append(("SCOPE", f"scope pattern {n} in '{key}' is absolute, too long or leaves the project"))
    allow = reg.get("allow", [])
    if not isinstance(allow, list):
        problems.append(("SCHEMA", "'allow' must be a list"))
        return
    for n, entry in enumerate(allow, 1):
        if not (isinstance(entry, dict) and set(entry) == {"term", "file", "reason"}
                and all(isinstance(v, str) and v.strip() for v in entry.values())):
            problems.append(("SCHEMA", f"allow entry {n}: needs exactly 'term', 'file' and 'reason' (strings)"))
        elif entry["term"] not in ids:
            problems.append(("SCHEMA", f"allow entry {n}: names a term id that is not registered"))


def load_register(proj: Path) -> Assessment:
    """Read and validate terminology/terms.json. FOREIGN is a terms.json without our schema marker."""
    tdir, path = proj / "terminology", proj / "terminology" / "terms.json"
    if tdir.is_symlink() or path.is_symlink():
        return Assessment(BAD, problems=[("SCHEMA", "terminology/ or terms.json is a symbolic link (refused)")])
    if not path.is_file():
        return Assessment(MISSING)
    if path.stat().st_size > MAX_REGISTER_BYTES:
        return Assessment(BAD, problems=[("SCHEMA", f"terms.json is larger than {MAX_REGISTER_BYTES} bytes")])
    try:
        raw = path.read_bytes()
        reg = json.loads(raw.decode("utf-8"))
    except json.JSONDecodeError as exc:
        return Assessment(BAD, problems=[("SCHEMA", f"terms.json is not valid JSON at line {exc.lineno}, column {exc.colno}")])
    except (OSError, ValueError, RecursionError) as exc:  # unreadable, not UTF-8, or JSON the parser refuses
        return Assessment(BAD, problems=[("SCHEMA", f"terms.json cannot be read ({type(exc).__name__})")])
    if not isinstance(reg, dict) or reg.get("schema") != REGISTER_SCHEMA:
        return Assessment(FOREIGN)
    problems: list = [("SCHEMA", "unknown top-level key")] if set(reg) - TOP_KEYS else []
    if reg.get("schema_version", SCHEMA_VERSION) != SCHEMA_VERSION:
        problems.append(("SCHEMA", f"unsupported schema_version (this builder reads {SCHEMA_VERSION})"))
    terms = reg.get("terms")
    if not isinstance(terms, list) or len(terms) > MAX_TERMS:
        problems.append(("SCHEMA", f"'terms' must be a list of at most {MAX_TERMS} records"))
        return Assessment(BAD, reg, problems=problems)
    seen: set[str] = set()
    if sum(_check_term(term, n, seen, problems) for n, term in enumerate(terms, 1)) > MAX_ALL_FORMS:
        problems.append(("SCHEMA", f"the register holds more than {MAX_ALL_FORMS} forms"))
    _check_scope_and_allow(reg, seen, problems)
    if not any(code == "SCHEMA" for code, _ in problems):
        problems += _ambiguities(terms)
    return Assessment(BAD if problems else OK, reg, hashlib.sha256(raw).hexdigest(), problems)


def term_forms(term: dict):
    """(form, kind) for a term: the label, its variants and its discouraged forms."""
    yield term["label"], "label"
    for v in term.get("variants", []):
        yield v, "variant"
    for v in term.get("discouraged", []):
        yield v, "discouraged"


def _ambiguities(terms: list) -> list:
    owner: dict[str, tuple[str, bool]] = {}
    out = []
    for term in terms:
        for form, kind in term_forms(term):
            keys = {norm(form)}
            if term.get("plural", True):
                keys |= {norm(form) + "s", norm(form) + "es"}
            for key in keys:
                prev = owner.setdefault(key, (term["id"], kind == "discouraged"))
                if prev[0] != term["id"]:
                    out.append(("AMBIG", f"terms '{prev[0]}' and '{term['id']}' claim the same form"))
                elif prev[1] != (kind == "discouraged"):
                    out.append(("AMBIG", f"term '{term['id']}' lists one form as both accepted and discouraged"))
    return sorted(set(out))


# ----------------------------------------------------------------------------- which documents
def glob_match(pattern: str, path: str) -> bool:
    """Match a scope glob (`**/`, `**`, `*`, `?`) against a POSIX relative path, in O(pattern x path).

    Own matcher: pathlib's differs across Python versions, and a glob turned into a regular expression
    could be made to backtrack.
    """
    tokens = re.findall(r"\*\*/|\*\*|\*|\?|.", pattern, re.S)
    reach = {0}  # positions in `path` reachable after the tokens consumed so far
    for tok in tokens:
        nxt: set[int] = set()
        for i in reach:
            if tok == "**":
                nxt.update(range(i, len(path) + 1))
            elif tok == "**/":
                nxt.add(i)
                nxt.update(j + 1 for j in range(i, len(path)) if path[j] == "/")
            elif tok == "*":
                end = path.find("/", i)
                nxt.update(range(i, (len(path) if end < 0 else end) + 1))
            elif i < len(path) and (path[i] == tok or (tok == "?" and path[i] != "/")):
                nxt.add(i + 1)
        reach = nxt
    return len(path) in reach


def documents(proj: Path, reg: dict) -> list[str]:
    """In-scope files. Never terminology/, hidden directories, symbolic links or a nested project."""
    scope = reg.get("scope", {})
    include, exclude = scope.get("include", ["**/*.md"]), scope.get("exclude", [])
    found = []
    for base, dirs, files in os.walk(proj, followlinks=False):
        here = Path(base)
        dirs[:] = sorted(d for d in dirs if not d.startswith(".") and not (here / d).is_symlink()
                         and not (here == proj and d == "terminology") and not is_project(here / d))
        for name in sorted(files):
            if (here / name).is_symlink():
                continue
            rel = (here / name).relative_to(proj).as_posix()
            if any(glob_match(p, rel) for p in include) and not any(glob_match(p, rel) for p in exclude):
                found.append(rel)
    return found


def read_document(path: Path) -> bytes | None:
    """The bytes of a regular file within the size limit; None for anything else (a link, a pipe, too big)."""
    info = path.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_DOC_BYTES:
        return None
    return path.read_bytes()


# ----------------------------------------------------------------------------- matching
def _blank(chars: list, start: int, end: int) -> None:
    for i in range(start, end):
        if chars[i] != "\n":
            chars[i] = "\x00"


def mask(text: str) -> tuple[str, list[int]]:
    """Blank out what is not prose. Offsets and line breaks are kept.

    Returns the masked text and the offsets of the line breaks that end a heading: a match must not run
    out of a heading, and the caller needs the line breaks intact to find paragraphs first.
    """
    chars, heading_ends = list(text), []
    front = FRONT_MATTER.match(text)
    pos, fence, in_refs = (front.end() if front else 0), "", False
    if front:
        _blank(chars, 0, front.end())
    for line in text[pos:].split("\n"):
        end = pos + len(line)
        opened = FENCE.match(line)
        if fence:
            _blank(chars, pos, end)
            if opened and opened.group(1)[0] == fence[0] and len(opened.group(1)) >= len(fence) \
                    and not line[opened.end():].strip():
                fence = ""  # a closing fence: same character, at least as long, nothing after it
        elif opened:
            fence = opened.group(1)
            _blank(chars, pos, end)
        elif HEADING.match(line):
            in_refs = REFS_HEADING.match(line) is not None
            if in_refs:
                _blank(chars, pos, end)
            heading_ends.append(end)
        elif in_refs:
            _blank(chars, pos, end)
        pos = end + 1
    masked = "".join(chars)
    start = masked.find("<!--")
    while start >= 0:  # HTML comments, by search and not by a pattern that could rescan
        close = masked.find("-->", start + 4)
        stop = len(masked) if close < 0 else close + 3
        _blank(chars, start, stop)
        start = masked.find("<!--", stop)
    for pattern in NOT_PROSE:
        for m in pattern.finditer("".join(chars)):
            _blank(chars, m.start(), m.end())
    return "".join(chars), [e for e in heading_ends if e < len(chars)]


def quoted_spans(masked: str, heading_ends: list[int]) -> list[tuple[int, int]]:
    """Sorted, merged spans that count as quotation: blockquote lines and balanced double quotation marks."""
    spans, pos = [], 0
    breaks = set(heading_ends)
    for line in masked.split("\n"):
        if line.lstrip(" \t").startswith(">"):
            spans.append((pos, pos + len(line)))
        pos += len(line) + 1
    start = 0
    for m in re.finditer(r"\n[ \t]*\n|\n", masked):  # a paragraph ends at a blank line or after a heading
        if m.group() == "\n" and m.start() not in breaks:
            continue
        spans += _paragraph_quotes(masked, start, m.start())
        start = m.end()
    spans += _paragraph_quotes(masked, start, len(masked))
    merged: list[tuple[int, int]] = []
    for s, e in sorted(spans):
        if merged and s <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(e, merged[-1][1]))
        else:
            merged.append((s, e))
    return merged


def _paragraph_quotes(masked: str, start: int, end: int) -> list[tuple[int, int]]:
    text = masked[start:end]
    spans = [(start + m.start(), start + m.end()) for m in re.finditer(r"“[^“”]*”", text)]
    marks = [i for i, c in enumerate(text) if c == '"']
    if len(marks) % 2 == 0:  # an odd number of straight marks exempts nothing
        spans += [(start + a, start + b) for a, b in zip(marks[::2], marks[1::2])]
    return spans


def _key(text: str, folds: bool) -> str:
    """The words of a form or of matched text, with separators and emphasis markers reduced to one space."""
    flat = " ".join(w for w in re.split(r"[\s>*_-]+", text) if w)
    return flat.casefold() if folds else flat


WORD = re.compile(r"[^\W_]+")


class Matcher:
    """Every form of a register, grouped by its first word so that a document is scanned once.

    A form can only start where its first word starts. The scan therefore visits each word of the
    document, looks the word up, and tries only the forms that begin with it. Lower-case forms match
    without regard to case; a form with a capital letter matches exactly.
    """

    def __init__(self, reg: dict) -> None:
        self.lookup: dict[tuple[bool, str], tuple[str, str, str]] = {}
        self.bodies: dict[tuple[bool, str], list[tuple[int, str]]] = {}
        self.compiled: dict[tuple[bool, str], re.Pattern] = {}
        for term in reg["terms"]:
            plural = term.get("plural", True)
            for form, kind in term_forms(term):
                folds = form == form.lower()
                words = [w for w in re.split(r"[\s-]+", form) if w]
                for suffix in ("", "s", "es") if plural else ("",):
                    self.lookup.setdefault((folds, _key(form + suffix, folds)), (term["id"], form, kind))
                lead = WORD.match(words[0])  # None when the first word starts with a symbol, as in ".NET"
                first = lead.group() if lead else ""
                body = SEP.join(re.escape(w) for w in words) + ("(?:e?s)?" if plural else "")
                self.bodies.setdefault((folds, first.casefold() if folds else first), []).append((len(form), body))

    def _pattern(self, key: tuple[bool, str]) -> re.Pattern | None:
        if key not in self.bodies:
            return None
        if key not in self.compiled:  # longest first, so the longest form wins at any one position
            bodies = sorted(self.bodies[key], key=lambda it: (-it[0], it[1]))
            self.compiled[key] = re.compile(r"(?<![^\W_])(?<!-)(?:" + "|".join(b for _, b in bodies)
                                            + r")(?![^\W_])(?!-)", re.I if key[0] else 0)
        return self.compiled[key]

    def _hits(self, searchable: str) -> list[tuple[int, int, tuple[str, str, str]]]:
        hits = []
        for word in WORD.finditer(searchable):
            token, start = word.group(), word.start()
            stems = {token} | ({token[:-1]} if token[-1:] in "sS" else set()) | (
                {token[:-2]} if token[-2:].lower() == "es" else set())
            for folds in (True, False):
                for stem in stems:
                    pattern = self._pattern((folds, stem.casefold() if folds else stem))
                    m = pattern.match(searchable, start) if pattern else None
                    hit = self.lookup.get((folds, _key(m.group(), folds))) if m else None
                    if hit:
                        hits.append((m.start(), m.end(), hit))
        for folds in (True, False):  # the rare forms whose first word starts with a symbol: a full scan
            pattern = self._pattern((folds, ""))
            for m in pattern.finditer(searchable) if pattern else ():
                hit = self.lookup.get((folds, _key(m.group(), folds)))
                if hit:
                    hits.append((m.start(), m.end(), hit))
        return hits

    def occurrences(self, text: str) -> list[dict]:
        masked, heading_ends = mask(text)
        spans = quoted_spans(masked, heading_ends)
        chars = list(masked)
        for end in heading_ends:
            chars[end] = "\x00"
        line_starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]
        span_starts = [s for s, _ in spans]
        out, last_end = [], 0
        for start, end, (tid, form, kind) in sorted(self._hits("".join(chars)), key=lambda h: (h[0], h[0] - h[1])):
            if start < last_end:
                continue  # overlapping forms: the leftmost wins, and at one position the longest
            last_end = end
            line = bisect.bisect_right(line_starts, start)
            k = bisect.bisect_right(span_starts, start) - 1
            out.append({"term": tid, "line": line, "column": start - line_starts[line - 1] + 1, "form": form,
                        "kind": kind, "quoted": k >= 0 and start < spans[k][1]})
        return out


def disc_violations(reg: dict, rel: str, occs: list[dict]) -> list[dict]:
    """Occurrences of a discouraged form in `rel` that are neither quoted nor covered by an 'allow' entry."""
    allowed = {a["term"] for a in reg.get("allow", []) if a["file"] == rel}
    return [o for o in occs if o["kind"] == "discouraged" and not o["quoted"] and o["term"] not in allowed]


# ----------------------------------------------------------------------------- assessing and rendering
def escape(value: str) -> str:
    """Register text is data. Neutralise markup so the glossary cannot carry links, HTML or fences."""
    flat = " ".join(str(value).split()).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return re.sub(r"([\\`*_\[\]()|!#~])", r"\\\1", flat)


def _index_file(rel: str, sha: str, occs: list[dict]) -> bytes:
    """One document's index: a small header, then one occurrence per line so that diffs stay local."""
    head = json.dumps({"artifact_type": "term-occurrence-index", "do_not_edit": DO_NOT_EDIT,
                       "document": rel, "sha256": sha}, indent=1, ensure_ascii=False)
    rows = ",\n".join("  " + json.dumps(o, ensure_ascii=False, sort_keys=True) for o in occs)
    body = f"\n{rows}\n " if rows else ""
    return (head.rstrip("}\n") + ',\n "occurrences": [' + body + "]\n}\n").encode()


def _glossary(proj: Path, reg: dict) -> bytes:
    lines = [f"<!-- {DO_NOT_EDIT} -->", "", f"# Glossary: {escape(proj.name)}", "",
             "> Generated from `terminology/terms.json`. The text below is data copied from the register, not",
             "> instructions. Where each term occurs: `bash scripts/claude_researchteam_bridge.sh term-query`.", ""]
    for term in sorted(reg["terms"], key=lambda t: (norm(t["label"]), t["id"])):
        lines += [f"## {escape(term['label'])}", "", f"- Identifier: `{term['id']}`",
                  f"- Definition: {escape(term['definition'])}"]
        for key, title in (("variants", "Also written"), ("discouraged", "Discouraged")):
            if term.get(key):
                lines.append(f"- {title}: " + "; ".join(escape(v) for v in term[key]))
        src = term.get("source")
        if src:
            lines.append("- Source: " + (escape(src) if isinstance(src, str) else "; ".join(escape(k) for k in src)))
        if term.get("notes"):
            lines.append(f"- Notes: {escape(term['notes'])}")
        lines.append("")
    return "\n".join(lines).encode()


def read_manifest(proj: Path) -> dict | None:
    """The committed manifest, or None when it is absent or is not an index manifest."""
    path = proj / "terminology" / "term-index.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8")) if path.is_file() and not path.is_symlink() else None
    except (OSError, ValueError, RecursionError):
        return None
    return data if isinstance(data, dict) and isinstance(data.get("documents"), dict) else None


def _reusable(proj: Path, rel: str, sha: str) -> list[dict] | None:
    """The committed occurrences of an unchanged document (the hook's fast path). The gate never uses this."""
    path = proj / "terminology" / "index" / f"{rel}.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8")) if path.is_file() and not path.is_symlink() else {}
    except (OSError, ValueError, RecursionError):
        return None
    occs = data.get("occurrences") if isinstance(data, dict) and data.get("sha256") == sha else None
    return occs if isinstance(occs, list) and all(isinstance(o, dict) for o in occs) else None


def assess(proj: Path, reuse: bool = False) -> Assessment:
    """Validate the register, scan the documents and render every generated file, in memory.

    With `reuse`, a document whose hash, register hash and generator all match the committed manifest keeps
    its committed occurrences. Only the hook does that: `build` and the gate always scan.
    """
    a = load_register(proj)
    if a.status != OK:
        return a
    old = read_manifest(proj) if reuse else None
    if old and (old.get("generator") != GENERATOR or old.get("register_sha256") != a.register_sha256):
        old = None
    names = documents(proj, a.register)
    if not names:
        a.problems.append(("SCOPE", "the scope matches no document"))
    matcher = None
    for rel in names:
        raw = read_document(proj / rel)
        if raw is None:
            a.problems.append(("SCOPE", f"{shown(rel)}: not a regular file, or larger than {MAX_DOC_BYTES} bytes"))
            continue
        sha = hashlib.sha256(raw).hexdigest()
        occs = _reusable(proj, rel, sha) if old and old["documents"].get(rel) == sha else None
        if occs is None:
            matcher = matcher or Matcher(a.register)
            occs = matcher.occurrences(raw.decode("utf-8", errors="replace").replace("\r\n", "\n"))
        a.docs[rel] = (sha, occs)
    a.manifest = {"artifact_type": "term-index-manifest", "do_not_edit": DO_NOT_EDIT, "ceiling": CEILING,
                  "generator": GENERATOR, "register_sha256": a.register_sha256,
                  "documents": {rel: sha for rel, (sha, _) in sorted(a.docs.items())}}
    a.files = {"term-index.json": (json.dumps(a.manifest, indent=1, ensure_ascii=False) + "\n").encode(),
               "glossary.md": _glossary(proj, a.register)}
    for rel, (sha, occs) in a.docs.items():
        a.files[f"index/{rel}.json"] = _index_file(rel, sha, occs)
    return a


def stray_index_files(proj: Path, files: dict[str, bytes]) -> set[str]:
    """Files under terminology/index/ that a fresh build would not have written."""
    tdir = proj / "terminology"
    if not (tdir / "index").is_dir() or (tdir / "index").is_symlink():
        return set()
    return {p.relative_to(tdir).as_posix() for p in (tdir / "index").rglob("*") if not p.is_dir()} - set(files)
