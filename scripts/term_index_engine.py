#!/usr/bin/env python3
"""The term-index engine: researchteam's adapters over the pinned agentteams term-index core.

Purpose: the one implementation behind docs/term-index-protocol.md. build_term_index.py,
    check_term_index.py and query_term_index.py import this module, so they read a register and match
    text in exactly the same way. Register validation, masking, matching, rendering and the comparison
    with the committed index are the core's: a byte-identical copy of agentteams' term_index.py and
    _term_text.py in scripts/term-index-core/, checked against PINNED.json and loaded by
    check_term_core.py. This file holds what is researchteam's: Projects/ discovery, the research-project
    predicate, the reference-section skip, the generator and banner names, the manifest fast path the
    hook uses, and wrappers that pass researchteam's configuration to every core call. Nothing here
    writes a file.
Lifecycle: UTILITY
Created: 2026-11-16

CEILING (do not soften): matching finds forms, not meanings. An occurrence is a place where a registered
form appears. It is not evidence that the term is used in its defined sense.

Not a command: import it. RT_ROOT=<path> overrides the repository root (test harness). Standard library
only; an installed agentteams is never imported. Importing this module checks the pinned core first and
exits 2 with the check's lines if it does not verify. GENERATOR must change whenever the bytes of a
generated file would change for the same inputs: the gate uses it to tell an upgrade of these scripts
(advisory) from a hand edit (blocking).

Every wrapper takes researchteam's configuration and the composite project predicate; none of the core's
functions is exported bare, because the core's neutral defaults (no reference-section skip, the agentteams
generator, both register schemas, nested projects only when they hold a register) would change results.
"""
from __future__ import annotations

import dataclasses
import hashlib
import os
import re
import sys
from pathlib import Path

try:
    import check_term_core
except ModuleNotFoundError as exc:
    if exc.name != "check_term_core":
        raise
    print("[term-core] MISSING scripts/check_term_core.py: the term index cannot load its pinned core.\n"
          "[term-core] This happens when an older researchteam synced the new term-index scripts: its file list "
          "does not include scripts/check_term_core.py or scripts/term-index-core/. Upgrade researchteam first "
          "(bash scripts/bootstrap_toolchain.sh, or pip install researchteam at the tag toolchain.lock names), "
          "then run researchteam update. Re-running the older researchteam's update changes nothing.",
          file=sys.stderr)
    raise SystemExit(2) from None

try:
    core = check_term_core.load()
except check_term_core.CoreCheckFailed as exc:
    print("\n".join(exc.lines), file=sys.stderr)
    raise SystemExit(2) from None

GENERATOR = "researchteam-term-index/1"
REGISTER_SCHEMA = core.RESEARCHTEAM_SCHEMA  # "researchteam-term-register"
SCHEMA_VERSION, CEILING = core.SCHEMA_VERSION, core.CEILING
DO_NOT_EDIT = ("GENERATED by scripts/build_term_index.py from terminology/terms.json. Do not edit. "
               "Rebuild: bash scripts/claude_researchteam_bridge.sh term-build <project>")
GLOSSARY_HINT = "Where each term occurs: `bash scripts/claude_researchteam_bridge.sh term-query`."
MAX_DOC_BYTES, MAX_DEPTH = core.MAX_DOC_BYTES, 12
MISSING, FOREIGN, BAD, OK = core.MISSING, core.FOREIGN, core.BAD, core.OK  # register status
Assessment = core.Assessment
# Directories the citation detector prunes when it looks for projects (check_citation_integrity.sh).
PRUNED_DIRS = {".agentteams-backups", ".git", "plans", "JSModules", "cssfiles", "node_modules"}
# The citation detector's reference-list headings (scripts/check_citation_integrity.sh, split_deliverable).
REFS_HEADING = re.compile(r"^#{1,6}[ \t]+([Rr]eferences|[Bb]ibliography|[Ww]orks [Cc]ited|[Ss]ources)([ \t].*)?$")

CONFIG = core.TermIndexConfig(generator=GENERATOR, dir_name="terminology", schemas=(REGISTER_SCHEMA,),
                              skip_heading=REFS_HEADING, source_validator=None, region_filter=None,
                              default_include=("**/*.md",), do_not_edit=DO_NOT_EDIT, rebuild_hint="term-build",
                              glossary_hint=GLOSSARY_HINT)


# ----------------------------------------------------------------------------- locating projects
def repo_root() -> Path:
    return Path(os.environ.get("RT_ROOT") or Path(__file__).parent.parent).resolve()


def is_research_project(d: Path) -> bool:
    """The citation detector's predicate: a research plan, a references/ directory, or an NN-*.md file."""
    if (d / "00-research-plan.md").is_file() or (d / "references").is_dir():
        return True
    return any(re.match(r"[0-9][0-9]-.*\.md$", p.name) for p in d.iterdir() if p.is_file())


def is_project(d: Path) -> bool:
    return any((d / "terminology" / f).exists() for f in ("terms.json", "term-index.json")) or is_research_project(d)


def discover(root: Path) -> list[Path]:
    """Every project under Projects/, nested ones included, down to MAX_DEPTH levels.

    The search follows the citation detector's: every directory but the pruned names. It differs in
    four ways, stated in the protocol: only Projects/ is searched, it stops at MAX_DEPTH, a project's
    own `terminology` folder (its register) is not searched, and a directory that holds a register is
    a project even without a research marker.
    """
    return core.discover(root / "Projects", is_project, pruned=frozenset(PRUNED_DIRS), skip_dir="terminology",
                         max_depth=MAX_DEPTH)


def project_arg(target: str) -> str:
    """A project named on the command line, as a POSIX path relative to Projects/."""
    wanted = target.replace("\\", "/").strip("/")
    return wanted[len("Projects/"):] if wanted.startswith("Projects/") else wanted


def resolve(root: Path, target: str) -> Path | None:
    """A discovered project, by its path under Projects/ or by a directory name that is unique."""
    wanted, projects = project_arg(target), discover(root)
    by_path = [p for p in projects if p.relative_to(root / "Projects").as_posix() == wanted]
    by_name = [p for p in projects if p.name == wanted]
    return by_path[0] if by_path else (by_name[0] if len(by_name) == 1 else None)


# ----------------------------------------------------------------------------- the core, with researchteam's configuration
def shown(path: str) -> str:
    """A path for a message an agent will read: withheld unless it is made of plain characters."""
    return core.shown(path)


def form_key(text: str, *, folds: bool = True) -> str:
    """The one test of whether two forms, or a form and matched text, are the same."""
    return core.form_key(text, folds)


def glob_match(pattern: str, path: str) -> bool:
    """Match a scope glob (`**/`, `**`, `*`, `?`) against a POSIX relative path, in linear time."""
    return core.glob_match(pattern, path)


def term_forms(term: dict) -> list[tuple[str, str]]:
    """(form, kind) for a term: the label, its variants and its discouraged forms."""
    return core.term_forms(term)


def load_register(proj: Path) -> Assessment:
    """Read and validate terminology/terms.json. FOREIGN is a terms.json without researchteam's schema marker."""
    return core.load_register(proj, CONFIG)


def documents(proj: Path, reg: dict) -> list[str]:
    """In-scope files. Never terminology/, hidden directories, symbolic links or a nested project."""
    return core.documents(proj, reg, CONFIG, is_project)


def read_document(proj: Path, rel: str) -> bytes | None:
    """The bytes of a document within the size limit, reached through no link; None for anything else."""
    return core.read_document(proj / rel, proj)


class Matcher(core.Matcher):
    """The core's matcher, skipping researchteam's reference sections unless told otherwise."""

    def __init__(self, reg: dict, *, skip_heading: re.Pattern | None = REFS_HEADING) -> None:
        super().__init__(reg, skip_heading)


def disc_violations(reg: dict, rel: str, occs: list[dict]) -> list[dict]:
    """Occurrences of a discouraged form in `rel` that are neither quoted nor covered by an 'allow' entry."""
    return core.disc_violations(reg, rel, occs)


def read_manifest(proj: Path) -> dict | None:
    """The committed manifest, or None when it is absent or is not an index manifest."""
    return core.read_manifest(proj, CONFIG)


def assess(proj: Path, *, reuse: bool = False) -> Assessment:
    """Validate the register, scan the documents and render every generated file, in memory. With
    `reuse` (the hook only), a document whose hash, register hash and generator all match the committed
    manifest keeps its committed occurrences. `build` and the gate always scan."""
    return core.assess(proj, CONFIG, reuse=reuse, is_project=is_project)


def stray_index_files(proj: Path, files: dict[str, bytes]) -> set[str]:
    """Files under terminology/index/ that a fresh build would not have written."""
    return core.stray_index_files(proj, files, CONFIG)


def check_register(proj: Path, *, source_validator) -> tuple[bool, list, list]:
    """The core's check of a project whose register loads: (checked, defects, reviews). The caller handles a
    missing or foreign register itself, so the NOREG wording stays researchteam's (seam table, gap 2)."""
    config = dataclasses.replace(CONFIG, source_validator=source_validator)
    return core.check_project(proj, config, required=False, indexed=True, is_project=is_project)


# ----------------------------------------------------------------------------- the hook's fast path (seam table, gap 3)
def manifest_matches(old: dict | None, register_sha256: str) -> bool:
    """Whether a committed manifest was written by this generator for this register."""
    return bool(old) and old.get("generator") == CONFIG.generator and old.get("register_sha256") == register_sha256


def manifest_is_current(proj: Path) -> bool:
    """True when the committed manifest already describes the register and every in-scope document."""
    a, old = load_register(proj), read_manifest(proj)
    if a.status != OK or not manifest_matches(old, a.register_sha256):
        return False
    current = {}
    for rel in documents(proj, a.register):
        raw = read_document(proj, rel)
        current[rel] = hashlib.sha256(raw).hexdigest() if raw is not None else None
    return current == old["documents"]
