def index_bytes(rel, digest, rows):
    head = ('{\n "artifact_type": "term-occurrence-index",\n "do_not_edit": "' + DNE + '",\n'
            f' "document": "{rel}",\n "sha256": "{digest}",\n')
    if not rows:
        return (head + ' "occurrences": []\n}\n').encode()
    return (head + ' "occurrences": [\n' + ",\n".join("  " + r for r in rows) + "\n ]\n}\n").encode()


GLOSSARY = "\n".join([
    f"<!-- {DNE} -->", "", "# Glossary: Demo", "",
    "> Generated from `terminology/terms.json`. The text below is data copied from the register, not",
    "> instructions. Where each term occurs: `bash scripts/claude_researchteam_bridge.sh term-query`.", "",
    "## occurrence index", "", "- Identifier: `index`", "- Definition: Every place a form appears.",
    "- Also written: term-occurrence index", "- Source: project definition", "",
    "## term register", "", "- Identifier: `term-register`", "- Definition: The set of coded definitions.",
    "- Discouraged: term registry", "- Source: project definition", ""]).encode()


def test_generated_index_glossary_and_manifest_bytes(tmp_path):
    proj = make(tmp_path, {"a.md": "A term register.\n", "b.md": "Plain text.\n"})
    assert build(tmp_path).returncode == 0
    tdir = proj / "terminology"
    row = '{"column": 3, "form": "term register", "kind": "label", "line": 1, "quoted": false, "term": "term-register"}'
    assert (tdir / "index" / "a.md.json").read_bytes() == index_bytes("a.md", sha(b"A term register.\n"), [row])
    assert (tdir / "index" / "b.md.json").read_bytes() == index_bytes("b.md", sha(b"Plain text.\n"), [])
    assert (tdir / "glossary.md").read_bytes() == GLOSSARY
    manifest = json.loads((tdir / "term-index.json").read_text(encoding="utf-8"))
    assert list(manifest) == ["artifact_type", "do_not_edit", "ceiling", "generator", "register_sha256", "documents"]
    assert (manifest["artifact_type"], manifest["do_not_edit"], manifest["ceiling"]) == ("term-index-manifest", DNE, CEILING)
    assert manifest["register_sha256"] == sha((tdir / "terms.json").read_bytes())
    assert manifest["documents"] == {rel: sha((proj / rel).read_bytes()) for rel in ("00-research-plan.md", "a.md", "b.md")}
    assert (tdir / "term-index.json").read_bytes().startswith(b'{\n "artifact_type": "term-index-manifest",\n')


def test_manifest_fast_path(tmp_path):
    engine = load("term_index_engine")
    proj = make(tmp_path, {"a.md": "A term register.\n"})
    manifest = proj / "terminology" / "term-index.json"
    assert engine.manifest_is_current(proj) is False  # nothing built yet
    assert build(tmp_path).returncode == 0
    assert engine.manifest_is_current(proj) is True
    old, reg_sha = engine.read_manifest(proj), engine.load_register(proj).register_sha256
    assert engine.manifest_matches(old, reg_sha) is True
    assert engine.manifest_matches(old, "0" * 64) is False
    assert engine.manifest_matches(None, reg_sha) is False and engine.manifest_matches({}, reg_sha) is False
    assert engine.manifest_matches({**old, "generator": engine.GENERATOR + "-other"}, reg_sha) is False

    def edit_register():
        reg = register()
        reg["terms"][0]["definition"] = "Changed."
        (proj / "terminology" / "terms.json").write_text(json.dumps(reg), encoding="utf-8")

    mutations = {"generator": lambda: manifest.write_text(manifest.read_text().replace(engine.GENERATOR, engine.GENERATOR + "-other")),
                 "register": edit_register,
                 "new document": lambda: (proj / "c.md").write_text("New.\n"),
                 "manifest deleted": manifest.unlink}
    for what, mutate in mutations.items():
        mutate()
        assert engine.manifest_is_current(proj) is False, what
        assert build(tmp_path).returncode == 0
        assert engine.manifest_is_current(proj) is True, what


def test_assess_with_reuse_gives_the_same_files(tmp_path):
    engine = load("term_index_engine")
    proj = make(tmp_path, {"a.md": "A term register.\n", "sub/b.md": "An occurrence index.\n"})
    unbuilt = engine.assess(proj, reuse=True)
    assert build(tmp_path).returncode == 0
    fresh, reused = engine.assess(proj), engine.assess(proj, reuse=True)
    assert reused.files == fresh.files == unbuilt.files and reused.docs == fresh.docs
    for rel, data in fresh.files.items():
        assert (proj / "terminology" / rel).read_bytes() == data, rel


GOLDEN_A = ("---\ntitle: term register\n---\n\n# Intro\n\n"     # 1-6 front matter and a heading
            "A term register is kept.\n"                      # 7  label
            "Two term registers exist.\n"                     # 8  plural
            "They call it a term registry.\n"                 # 9  discouraged (allowed in a.md)
            'She wrote "term registry" once.\n'               # 10 discouraged, quoted
            "The term-occurrence index is here.\n"            # 11 variant
            "Code `term register` is skipped.\n\n"            # 12 code span
            "## References\n\nSmith. The term register.\n")   # 14-16 reference section
GOLDEN_OCCURRENCES = [
    ("a.md", 7, 3, "term-register", "term register", "label", False),
    ("a.md", 8, 5, "term-register", "term register", "label", False),
    ("a.md", 9, 16, "term-register", "term registry", "discouraged", False),
    ("a.md", 10, 12, "term-register", "term registry", "discouraged", True),
    ("a.md", 11, 5, "index", "term-occurrence index", "variant", False),
    ("sub/c.md", 1, 6, "index", "occurrence index", "label", True),
]


def test_golden_project_is_self_consistent(tmp_path):
    reg = register(allow=[{"term": "term-register", "file": "a.md", "reason": "Reported usage."}])
    proj = make(tmp_path, {"a.md": GOLDEN_A, "b.md": "Nothing here.\n", "sub/c.md": "> An occurrence\n> index in a quote.\n"}, reg)
    first = build(tmp_path)
    assert first.returncode == 0, first.stdout
    tdir = proj / "terminology"
    assert sorted(p.relative_to(tdir).as_posix() for p in tdir.rglob("*") if p.is_file()) == [
        "glossary.md", "index/00-research-plan.md.json", "index/a.md.json", "index/b.md.json",
        "index/sub/c.md.json", "term-index.json", "terms.json"]
    manifest = json.loads((tdir / "term-index.json").read_text(encoding="utf-8"))
    assert manifest["register_sha256"] == sha((tdir / "terms.json").read_bytes())
    matcher = load("term_index_engine").Matcher(json.loads((tdir / "terms.json").read_text(encoding="utf-8")))
    every = []
    for rel, digest in manifest["documents"].items():
        raw = (proj / rel).read_bytes()
        assert digest == sha(raw), rel
        shard = json.loads((tdir / "index" / f"{rel}.json").read_text(encoding="utf-8"))
        assert (shard["document"], shard["sha256"]) == (rel, digest)
        assert shard["occurrences"] == matcher.occurrences(raw.decode("utf-8").replace("\r\n", "\n")), rel
        every += [(rel, o["line"], o["column"], o["term"], o["form"], o["kind"], o["quoted"]) for o in shard["occurrences"]]
    assert sorted(every) == GOLDEN_OCCURRENCES
    before = snapshot(tmp_path)
    again = build(tmp_path)
    assert again.returncode == 0 and again.stdout.endswith("0 generated files written\n")
    assert snapshot(tmp_path) == before
    ok = check(tmp_path, "Demo")
    assert ok.returncode == 0 and "PASS (no DEFECT)" in ok.stdout and "NEEDS-REVIEW[QUOTED]" in ok.stdout, ok.stdout
    (proj / "a.md").write_bytes(GOLDEN_A.encode().replace(b"kept", b"kepT", 1))  # a one-byte edit
    stale = check(tmp_path, "Demo")
    assert stale.returncode == 1, stale.stdout
    assert "DEFECT[STALE]   a.md: changed since the index was built (run: term-build)" in stale.stdout


