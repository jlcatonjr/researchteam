SCENARIOS = (scenario_clean_build_check_query, scenario_staleness, scenario_usage_findings,
             scenario_register_defects, scenario_which_projects, scenario_usage_errors)


def transcript(tmp_path: Path) -> str:
    out = []
    for scenario in SCENARIOS:
        root = tmp_path / scenario.__name__
        (root / "Projects").mkdir(parents=True)
        t = Transcript(root)
        t.note(f"=== {scenario.__name__}")
        scenario(t)
        out += t.lines
    return "\n".join(out) + "\n"


def test_transcript_is_unchanged(tmp_path):
    text = transcript(tmp_path)
    if os.environ.get("RT_REGENERATE_TRANSCRIPT") == "1":
        EXPECTED.parent.mkdir(exist_ok=True)
        EXPECTED.write_text(text, encoding="utf-8")
    expected = EXPECTED.read_text(encoding="utf-8")
    if text != expected:
        got, want = text.splitlines(), expected.splitlines()
        first = next((i for i, (g, w) in enumerate(zip(got, want)) if g != w), min(len(got), len(want)))
        context = "\n".join(f"  want: {w}\n  got:  {g}" for w, g in zip(want[first:first + 5], got[first:first + 5]))
        raise AssertionError(f"transcript differs from line {first + 1}:\n{context}")
