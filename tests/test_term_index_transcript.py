class Transcript:
    def __init__(self, root: Path):
        self.root, self.lines = root, []

    def run(self, script: str, *args: str, stdin: str | None = None, env: dict | None = None) -> int:
        full = {k: v for k, v in os.environ.items() if k not in ("TERM_INDEX_ADVISORY", "RT_ROOT")}
        full.update({"RT_ROOT": str(self.root), **(env or {})})
        r = subprocess.run([sys.executable, "-B", str(SCRIPTS / script), *args], input=stdin, capture_output=True,
                           text=True, env=full, timeout=120)
        shown_env = " ".join(f"{k}={v}" for k, v in sorted((env or {}).items()))
        self.lines.append(f"$ {shown_env + ' ' if shown_env else ''}{script} {' '.join(args)}".rstrip())
        if stdin is not None:
            self.lines.append(f"  stdin: {stdin}")
        self.lines += [f"  out| {ln}" for ln in r.stdout.splitlines()]
        self.lines += [f"  err| {ln}" for ln in r.stderr.splitlines()]
        self.lines.append(f"  exit {r.returncode}")
        return r.returncode

    def files(self, proj: Path) -> None:
        """The sha256 of every file under the project's terminology/ (generated bytes included)."""
        tdir = proj / "terminology"
        rel = proj.relative_to(self.root).as_posix()
        self.lines.append(f"# files under {rel}/terminology")
        for p in sorted(tdir.rglob("*")) if tdir.is_dir() else []:
            if p.is_file() and not p.is_symlink():
                self.lines.append(f"  {p.relative_to(tdir).as_posix()} {hashlib.sha256(p.read_bytes()).hexdigest()}")

    def note(self, text: str) -> None:
        self.lines.append(f"# {text}")


def register(terms=None, **extra) -> dict:
    """A register; its term records are copies, so no scenario can change another's."""
    return {"schema": "researchteam-term-register", "schema_version": "1.0",
            "terms": copy.deepcopy(TERMS if terms is None else terms), **extra}


def project(root: Path, name: str, docs: dict, reg=None, raw: str | None = None, marker: bool = True) -> Path:
    proj = root / "Projects" / name
    proj.mkdir(parents=True, exist_ok=True)
    for rel, text in {**({"00-research-plan.md": "# Plan\n"} if marker else {}), **docs}.items():
        (proj / rel).parent.mkdir(parents=True, exist_ok=True)
        (proj / rel).write_text(text, encoding="utf-8")
    if reg is not None or raw is not None:
        (proj / "terminology").mkdir(exist_ok=True)
        (proj / "terminology" / "terms.json").write_text(raw if raw is not None else json.dumps(reg, indent=2),
                                                         encoding="utf-8")
    return proj


