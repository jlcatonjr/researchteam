#!/usr/bin/env bash
# INVESTIGATION RECORD (P5, 2026-11-14): run by hand, needs network; not for CI. Writes only under $WORK.
# Reproduce: does `researchteam update --ref v1.1.4` overwrite a frozen (codex) root AGENTS.md?
# Usage: WORK=<empty scratch dir> [MODE=handwritten|fenced|guard] bash repro.sh
# Evidence for references/plans/open-p5-agents-md-overwrite.plan.md; results in repro-result.md.
# Needs network (GitHub tarball/raw for v1.1.3 and v1.1.4). Installs nothing.
set -euo pipefail
# Refuse anything but an empty scratch directory outside every git worktree, so nothing lands in a real repository.
[ -n "${WORK:-}" ] || { echo "set WORK to an empty scratch dir" >&2; exit 1; }
[ -d "$WORK" ] && [ -z "$(ls -A "$WORK")" ] || { echo "WORK must be an existing, empty directory" >&2; exit 1; }
if git -C "$WORK" rev-parse --git-dir >/dev/null 2>&1; then echo "WORK is inside a git worktree; refusing" >&2; exit 1; fi
SRC="${SRC:-$HOME/githubrepositories/researchteam}"
PY="$SRC/.venv/bin/python"                    # has the pinned agentteams 1.1.3 beside it
WORK="${WORK:?set WORK to an empty scratch dir}"
export PYTHONPATH="$SRC"                      # run researchteam from source (main = v1.1.4 + docs)
export GIT_CONFIG_GLOBAL=/dev/null GIT_AUTHOR_NAME=repro GIT_AUTHOR_EMAIL=repro@example.invalid \
       GIT_COMMITTER_NAME=repro GIT_COMMITTER_EMAIL=repro@example.invalid
# NOTE: before the P5 fix (researchteam/__main__.py), `python -m researchteam.cli` silently did nothing, so this
# script calls main() directly.
rt() { "$PY" -c 'import sys; sys.argv[0]="researchteam"; from researchteam.cli import main; main()' "$@"; }

if [ "${MODE:-}" = guard ]; then
  # Offline check of researchteam's own restore layer: a body that overwrites AGENTS.md inside _guarded.
  cat > "$WORK/guard_check.py" <<'GUARD'
"""Exercise researchteam's _guarded restore directly (no network, no agentteams)."""
import json, subprocess, sys, tempfile
from pathlib import Path
from researchteam import _update_cmd as u

def case(name, brief_frozen, rt_line):
    d = Path(tempfile.mkdtemp(prefix=f"g-{name}-", dir=sys.argv[1]))
    subprocess.run(["git", "init", "-q", str(d)], check=True)
    b = {"project_name": "X"}
    if brief_frozen is not None: b["frozen_surfaces"] = brief_frozen
    (d / "brief.json").write_text(json.dumps(b))
    (d / ".researchteam").write_text("ref = main\n" + (rt_line + "\n" if rt_line else ""))
    (d / "AGENTS.md").write_bytes(b"PROJECT-OWNED sentinel\n")
    subprocess.run(["git", "-C", str(d), "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(d), "-c", "user.name=r", "-c", "user.email=r@x.invalid", "commit", "-qm", "b", "--no-verify"], check=True)
    def body(frozen):  # stands in for an unfrozen (goose) render that writes the root AGENTS.md
        (d / "AGENTS.md").write_text("<!-- generated by agentteams for Goose -->\nFULL GOOSE AGENTS.md\n")
    try:
        u._guarded(d, False, body)
        out = "ran"
    except SystemExit as e:
        out = f"exit: {str(e).splitlines()[0][:110]}"
    print(f"{name:28} {out:40} AGENTS.md restored={ (d/'AGENTS.md').read_bytes()==b'PROJECT-OWNED sentinel\n' }")

case("brief+rt codex", ["codex"], "frozen_surfaces = codex")
case("brief codex only", ["codex"], None)
case("rt codex only (brief none)", None, "frozen_surfaces = codex")
case("brief goose", ["goose"], None)
GUARD
  "$PY" "$WORK/guard_check.py" "$WORK"; exit $?
fi

cd "$WORK"
rt init proj --ref v1.1.3 > "$WORK/init.log" 2>&1; echo "init exit: $?"
cd "$WORK/proj"
[ -d .git ] || git init -q -b main .
"$PY" - <<'PY'
import json, pathlib
p = pathlib.Path("brief.json"); b = json.loads(p.read_text()); b["frozen_surfaces"] = ["codex"]; b["project_name"] = "ReproProject"
p.write_text(json.dumps(b, indent=2) + "\n")
PY
grep -q '^frozen_surfaces' .researchteam || echo 'frozen_surfaces = codex' >> .researchteam
# MODE=handwritten (default): an unfenced project-owned AGENTS.md.
# MODE=fenced: keep the scaffold's fenced Goose AGENTS.md and add a project line outside the fences.
if [ "${MODE:-handwritten}" = fenced ]; then
  printf '\nsentinel-7f3c: project edit outside the fences, must survive update.\n' >> AGENTS.md
else
  printf '# PROJECT-OWNED AGENTS.md\n\nsentinel-7f3c: hand-written, must survive update.\n' > AGENTS.md
fi
cp AGENTS.md "$WORK/AGENTS.before.md"
git add -A && git commit -q --no-verify -m "baseline: frozen codex, project-owned AGENTS.md"

rt update --ref v1.1.4 --yes > "$WORK/update.log" 2>&1; echo "update exit: $?"
grep -n -i "Frozen surfaces\|restored\|FAILED\|AGENTS.md:\|bridges:\|native surface" "$WORK/update.log" | head -40
diff -u "$WORK/AGENTS.before.md" AGENTS.md > "$WORK/AGENTS.diff"; echo "AGENTS.md diff exit: $? (0 = unchanged)"
git status --porcelain | head -60
